CREATE TABLE IF NOT EXISTS rol (
	Id_R VARCHAR(2) NOT NULL,
	Tipo TEXT NOT NULL,
	PRIMARY KEY (Id_R)
)

CREATE TABLE IF NOT EXISTS profesor (
	Id_PF VARCHAR(3) NOT NULL,
	Id_R VARCHAR(2) NOT NULL,
	Nombre TEXT NOT NULL,
	PRIMARY KEY (Id_PF),
	FOREIGN KEY (Id_R) REFERENCES rol(Id_R)
)

CREATE TABLE IF NOT EXISTS clase (
	Id_CL VARCHAR(3) NOT NULL,
	Id_M VARCHAR(2) NOT NULL,
	Id_PM VARCHAR(3) NOT NULL,
    Id_V VARCHAR(2) NOR NULL,
	Id_PF VARCHAR(3) NOT NULL,
	Id_CAM VARCHAR(4) NOT NULL,
	PRIMARY KEY (Id_CL),
	FOREIGN KEY (Id_M) REFERENCES modalidad(Id_M),
    FOREIGN KEY (Id_PM) REFERENCES promocion(Id_PM),
    FOREIGN KEY (Id_V) REFERENCES vertical(Id_V),
    FOREIGN KEY (Id_PF) REFERENCES profesor(Id_PF),
    FOREIGN KEY (Id_CAM) REFERENCES campus(Id_CAM)
)

CREATE TABLE IF NOT EXISTS campus (
	Id_CAM VARCHAR(4) NOT NULL,
	Lugar TEXT NOT NULL,
	PRIMARY KEY (Id_CAM)
)

CREATE TABLE IF NOT EXISTS modalidad (
	Id_M VARCHAR(2) NOT NULL,
	Tipo TEXT NOT NULL,
	PRIMARY KEY (Id_M)
)

CREATE TABLE IF NOT EXISTS promocion (
	Id_PM VARCHAR(3) NOT NULL,
	Fecha DATE NOT NULL,
	PRIMARY KEY (Id_PM)
)

CREATE TABLE IF NOT EXISTS vertical (
	Id_V VARCHAR(2) NOT NULL,
	Nombre_V TEXT NOT NULL,
	PRIMARY KEY (Id_CAM)
)

CREATE TABLE IF NOT EXISTS alumnos (
	Id_AL VARCHAR(3) NOT NULL,
	Id_CL VARCHAR(3) NOT NULL,
	Nombre TEXT NOT NULL,
    Correo TEXT NOR NULL,
	PRIMARY KEY (Id_AL),
	FOREIGN KEY (Id_CL) REFERENCES clase(Id_CL)
)

CREATE TABLE IF NOT EXISTS proyectos (
	Id_PY VARCHAR(3) NOT NULL,
	Id_V VARCHAR(2) NOT NULL,
	Id_AL VARCHAR(3) NOT NULL,
    Nombre_PY TEXT NOR NULL,
	PRIMARY KEY (Id_PY),
	FOREIGN KEY (Id_V) REFERENCES vertical(Id_V),
    FOREIGN KEY (Id_AL) REFERENCES alumnos(Id_AL)
)

CREATE TABLE IF NOT EXISTS resultados (
	Id_PY VARCHAR(3) NOT NULL,
	Id_AL VARCHAR(3) NOT NULL,
    Calificacion TEXT NOR NULL,
	PRIMARY KEY (Id_PY,Id_AL),
	FOREIGN KEY (Id_PY) REFERENCES proyectos(Id_PY),
    FOREIGN KEY (Id_AL) REFERENCES alumnos(Id_AL)
)
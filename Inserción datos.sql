
-- ---------- 1. Tablas independientes ---------------------------------
CREATE TABLE rol (
    Id_R  VARCHAR(10) PRIMARY KEY,
    Tipo  VARCHAR(10) NOT NULL UNIQUE
);
CREATE TABLE vertical (
    Id_V      VARCHAR(10) PRIMARY KEY,
    Nombre_V  VARCHAR(30) NOT NULL UNIQUE
);
CREATE TABLE campus (
    Id_CAM VARCHAR(10) PRIMARY KEY,
    Lugar  VARCHAR(50) NOT NULL UNIQUE
);
CREATE TABLE modalidad (
    Id_M  VARCHAR(10) PRIMARY KEY,
    Tipo  VARCHAR(30) NOT NULL UNIQUE
);
CREATE TABLE promocion (
    Id_PM VARCHAR(10) PRIMARY KEY,
    Fecha DATE        NOT NULL UNIQUE,
    Mes   VARCHAR(20) NOT NULL
);

-- ---------- 2. Tablas que dependen de las anteriores -----------------
CREATE TABLE profesores (
    Id_PF  VARCHAR(10)  PRIMARY KEY,
    Id_R   VARCHAR(10)  NOT NULL REFERENCES rol(Id_R),
    Nombre VARCHAR(100) NOT NULL
);
CREATE TABLE proyectos (
    Id_PY     VARCHAR(10) PRIMARY KEY,
    Id_V      VARCHAR(10) NOT NULL REFERENCES vertical(Id_V),
    Nombre_PY VARCHAR(50) NOT NULL,
    UNIQUE (Id_V, Nombre_PY)
);
CREATE TABLE clase (
    Id_CL  VARCHAR(10) PRIMARY KEY,
    Id_M   VARCHAR(10) NOT NULL REFERENCES modalidad(Id_M),
    Id_PM  VARCHAR(10) NOT NULL REFERENCES promocion(Id_PM),
    Id_V   VARCHAR(10) NOT NULL REFERENCES vertical(Id_V),
    Id_CAM VARCHAR(10) NOT NULL REFERENCES campus(Id_CAM),
    Id_PF  VARCHAR(10) NULL     REFERENCES profesor(Id_PF)   -- NULL = clase sin profesor en el claustro
);

-- ---------- 3. Tablas que dependen de clase / profesor / proyectos ----
-- ---------- 3. Alumnos -------------------------------------------------
CREATE TABLE alumnos (
    Id_AL  VARCHAR(10)  PRIMARY KEY,
    Id_CL  VARCHAR(10)  NOT NULL REFERENCES clase(Id_CL),
    Nombre VARCHAR(100) NOT NULL,
    Correo VARCHAR(150) NOT NULL UNIQUE
);

-- ---------- 4. Resultados (alumno x proyecto) ------------------------
CREATE TABLE resultados (
    Id_PY        VARCHAR(10) NOT NULL REFERENCES proyectos(Id_PY),
    Id_AL        VARCHAR(10) NOT NULL REFERENCES alumnos(Id_AL),
    Calificacion VARCHAR(10) NOT NULL CHECK (Calificacion IN ('Apto', 'No Apto')),
    PRIMARY KEY (Id_PY, Id_AL)
);

